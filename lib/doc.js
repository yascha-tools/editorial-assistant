// "Lite markdown" document model.
//
// Articles are kept as plain text with three kinds of inline markup that the
// model can see and the editor can read in the text box:
//   *italic*   **bold**   [link text](https://url)
// plus "# Heading" and "> quote" lines. parseLite() turns that into
//   { text, marks: [{start, end, type: 'i'|'b'|'a'|'h'|'q', href}] }
// where `text` is the article without markup and paragraphs are separated by
// a blank line. AI results are located against `text`, so highlights always
// sit on the editor's original words — the article itself is never
// regenerated by the model.

(function (root) {
'use strict';

const PATTERNS = [
  { type: 'a', re: /\[([^\]\n]+?)\]\((https?:\/\/[^\s)]+)\)/ },
  { type: 'b', re: /\*\*(?=\S)([^*\n]+?)\*\*/ },
  { type: 'i', re: /(?<![*\w])\*(?=[^\s*])([^*\n]*?[^\s*])\*(?![*\w])/ },
];

function parseInline(str, base = 0) {
  let text = '';
  const marks = [];
  let rest = str;
  while (rest.length) {
    let best = null;
    for (const p of PATTERNS) {
      const m = p.re.exec(rest);
      if (m && (!best || m.index < best.m.index)) best = { p, m };
    }
    if (!best) { text += rest; break; }
    text += rest.slice(0, best.m.index);
    const inner = parseInline(best.m[1], base + text.length);
    const start = base + text.length;
    text += inner.text;
    marks.push(...inner.marks);
    marks.push({ start, end: base + text.length, type: best.p.type, href: best.p.type === 'a' ? best.m[2] : undefined });
    rest = rest.slice(best.m.index + best.m[0].length);
  }
  return { text, marks };
}

function parseLite(md) {
  const lines = String(md || '').replace(/\r\n?/g, '\n').split('\n').map(l => l.trim()).filter(Boolean);
  let text = '';
  const marks = [];
  lines.forEach((raw, idx) => {
    if (idx > 0) text += '\n\n';
    let line = raw;
    let kind = null;
    let m;
    if ((m = line.match(/^(#{1,6})\s+(.*)$/))) { kind = 'h'; line = m[2]; }
    else if ((m = line.match(/^>\s?(.*)$/))) { kind = 'q'; line = m[1]; }
    const start = text.length;
    const r = parseInline(line, start);
    text += r.text;
    marks.push(...r.marks);
    if (kind) marks.push({ start, end: text.length, type: kind });
  });
  return { text, marks };
}

function stripMarkup(s) {
  return parseInline(String(s || '').replace(/\s+/g, ' ').trim()).text;
}

// Normalized copy of a string plus a map back to original offsets: lower-case,
// curly quotes and dashes unified, whitespace collapsed.
function normalize(s) {
  let norm = '';
  const map = [];
  let prevSpace = false;
  for (let i = 0; i < s.length; i++) {
    let c = s[i];
    if (/\s/.test(c)) {
      if (prevSpace) continue;
      c = ' ';
      prevSpace = true;
    } else prevSpace = false;
    if ('‘’‚‛′`'.includes(c)) c = "'";
    else if ('“”„‟″'.includes(c)) c = '"';
    else if ('‐‑‒–—―'.includes(c)) c = '-';
    else if (c === '…') { for (const ch of '...') { norm += ch; map.push(i); } continue; }
    norm += c.toLowerCase();
    map.push(i);
  }
  return { norm, map };
}

function allIndexes(hay, needle) {
  const out = [];
  if (!needle) return out;
  let i = hay.indexOf(needle);
  while (i !== -1) { out.push(i); i = hay.indexOf(needle, i + 1); }
  return out;
}

/**
 * Find `quote` in the document text. Returns {start, end} in doc.text
 * coordinates, or null. `contextBefore` (a few words preceding the quote)
 * disambiguates repeated phrases; `used` lists ranges already claimed so a
 * second identical quote lands on the next occurrence.
 */
function locate(doc, quote, contextBefore = '', used = []) {
  if (!doc._norm) doc._norm = normalize(doc.text);
  const { norm, map } = doc._norm;
  const attempts = [];
  const q0 = normalize(stripMarkup(quote)).norm.trim();
  if (!q0) return null;
  attempts.push(q0);
  const trimmed = q0.replace(/^["'\s.,;:!?(]+|["'\s.,;:!?)]+$/g, '');
  if (trimmed && trimmed !== q0) attempts.push(trimmed);

  for (const q of attempts) {
    const hits = allIndexes(norm, q);
    if (!hits.length) continue;
    const toRange = h => ({ start: map[h], end: map[h + q.length - 1] + 1 });
    let ranked = hits;
    const ctx = normalize(stripMarkup(contextBefore)).norm.trim();
    if (ctx && hits.length > 1) {
      const tail = ctx.split(' ').slice(-4).join(' ');
      const withCtx = hits.filter(h => norm.slice(Math.max(0, h - tail.length - 40), h).includes(tail));
      if (withCtx.length) ranked = withCtx.concat(hits.filter(h => !withCtx.includes(h)));
    }
    const free = ranked.find(h => {
      const r = toRange(h);
      return !used.some(u => u.start === r.start && u.end === r.end);
    });
    return toRange(free !== undefined ? free : ranked[0]);
  }

  // Fuzzy fallback for long quotes the model slightly misquoted: anchor on the
  // first and last few words.
  const words = q0.split(' ');
  if (words.length >= 8) {
    const head = words.slice(0, 4).join(' ');
    const tail = words.slice(-4).join(' ');
    for (const h of allIndexes(norm, head)) {
      const t = norm.indexOf(tail, h + head.length);
      if (t !== -1 && t - h <= q0.length * 1.6) {
        return { start: map[h], end: map[t + tail.length - 1] + 1, approximate: true };
      }
    }
  }
  return null;
}

// Links in the article, with the sentence-ish context around each one.
function linksIn(doc) {
  return doc.marks.filter(m => m.type === 'a' && m.href).map(m => ({
    text: doc.text.slice(m.start, m.end),
    href: m.href,
    start: m.start,
    end: m.end,
  }));
}

// Heuristic: a short first paragraph without final punctuation is a title.
function guessTitle(md) {
  const lines = String(md || '').split('\n').map(l => l.trim()).filter(Boolean);
  if (lines.length < 3) return '';
  const first = stripMarkup(lines[0].replace(/^#+\s*/, ''));
  const words = first.split(/\s+/).length;
  if (/^#\s/.test(lines[0]) || (words <= 20 && !/[.:;,]$/.test(first))) return first;
  return '';
}


// Apply edits [{start, end, replacement, id}] (doc.text coordinates; the
// replacement may contain *italic*/**bold**/[link](url) markup) and return
// { doc, ranges: [{id, start, end}], skipped: [ids] }. Formatting outside the
// edited spans is preserved; overlapping edits are skipped.
function applyEdits(doc, edits) {
  const sorted = edits.filter(e => e.start != null && e.end != null && e.end >= e.start)
    .sort((a, b) => a.start - b.start || a.end - b.end);
  const chosen = [];
  const skipped = [];
  let lastEnd = -1;
  for (const e of sorted) {
    if (e.start < lastEnd) { skipped.push(e.id); continue; }
    chosen.push(e);
    lastEnd = e.end;
  }
  let text = doc.text;
  let marks = doc.marks.map(m => ({ ...m }));
  for (const e of [...chosen].reverse()) {
    const rep = parseInline(String(e.replacement || ''));
    const newLen = rep.text.length;
    const delta = newLen - (e.end - e.start);
    text = text.slice(0, e.start) + rep.text + text.slice(e.end);
    const next = [];
    for (const m of marks) {
      if (m.end <= e.start && !(m.end === e.start && m.start === e.start)) { next.push(m); continue; }
      if (m.start >= e.end) { next.push({ ...m, start: m.start + delta, end: m.end + delta }); continue; }
      if (m.start === e.start && m.end === e.end && rep.marks.length && m.type !== 'h' && m.type !== 'q') continue; // replacement brings its own formatting
      if (m.start <= e.start && m.end >= e.end) { next.push({ ...m, end: m.end + delta }); continue; }
      if (m.start < e.start) { next.push({ ...m, end: e.start }); continue; }
      if (m.end > e.end) { next.push({ ...m, start: e.start + newLen, end: m.end + delta }); continue; }
      // mark entirely inside the replaced span: dropped (replacement has its own)
    }
    for (const m of rep.marks) next.push({ ...m, start: m.start + e.start, end: m.end + e.start });
    marks = next.filter(m => m.end > m.start);
  }
  // Final positions of each applied edit
  const ranges = [];
  let shift = 0;
  for (const e of chosen) {
    const len = parseInline(String(e.replacement || '')).text.length;
    ranges.push({ id: e.id, start: e.start + shift, end: e.start + shift + len });
    shift += len - (e.end - e.start);
  }
  return { doc: { text, marks }, ranges, skipped };
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
}

// Clean semantic HTML for pasting into Google Docs or Substack.
function toHtml(doc) {
  const text = doc.text;
  const paras = [];
  let p = 0;
  while (p <= text.length) {
    const brk = text.indexOf('\n\n', p);
    const end = brk === -1 ? text.length : brk;
    if (end > p) paras.push([p, end]);
    if (brk === -1) break;
    p = brk + 2;
  }
  const inlineMarks = doc.marks.filter(m => m.type === 'i' || m.type === 'b' || m.type === 'a');
  const inline = (s, e) => {
    const pts = new Set([s, e]);
    for (const m of inlineMarks) { if (m.start > s && m.start < e) pts.add(m.start); if (m.end > s && m.end < e) pts.add(m.end); }
    const b = [...pts].sort((x, y) => x - y);
    let out = '';
    for (let i = 0; i < b.length - 1; i++) {
      const a = b[i], z = b[i + 1];
      let seg = escapeHtml(text.slice(a, z)).replace(/\n/g, '<br>');
      const act = inlineMarks.filter(m => m.start <= a && m.end >= z);
      if (act.some(m => m.type === 'b')) seg = `<strong>${seg}</strong>`;
      if (act.some(m => m.type === 'i')) seg = `<em>${seg}</em>`;
      const link = act.find(m => m.type === 'a');
      if (link) seg = `<a href="${escapeHtml(link.href)}">${seg}</a>`;
      out += seg;
    }
    return out;
  };
  let html = '';
  let list = false;
  for (const [s, e] of paras) {
    const block = doc.marks.find(m => (m.type === 'h' || m.type === 'q') && m.start <= s && m.end >= e);
    const raw = text.slice(s, e);
    const isItem = !block && /^[-•]\s/.test(raw);
    if (isItem && !list) { html += '<ul>'; list = true; }
    if (!isItem && list) { html += '</ul>'; list = false; }
    if (isItem) { html += `<li>${inline(s + 2, e)}</li>`; continue; }
    if (block && block.type === 'h') html += `<h2>${inline(s, e)}</h2>`;
    else if (block && block.type === 'q') html += `<blockquote><p>${inline(s, e)}</p></blockquote>`;
    else html += `<p>${inline(s, e)}</p>`;
  }
  if (list) html += '</ul>';
  return html;
}

const api = { parseLite, parseInline, stripMarkup, normalize, locate, linksIn, guessTitle, applyEdits, toHtml };
if (typeof module !== 'undefined' && module.exports) module.exports = api;
else root.LiteDoc = api;
})(typeof self !== 'undefined' ? self : this);
